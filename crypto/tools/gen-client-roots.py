#!/usr/bin/env python3
"""Generate the TLS fork's bundled root store from the node's pinned webpki-roots.

The client (TLS fork, utils/mozilla-root-cas.js) and the node (cu-sidecar,
webpki-roots) must trust the same roots: a client that trusts more than the node
accepts certificates that only an honest node's own check would catch. This
reads the PEM certificates that webpki-roots embeds (generated by that crate
from Mozilla's CCADB report) for the version pinned in crypto/Cargo.lock and
writes them as the fork's MOZILLA_ROOT_CA_LIST. Each certificate is paired with
its TrustAnchor; an anchor that webpki applies name constraints to is left out
(the fork reads constraints only from certificate extensions, so it would trust
that root more widely than the node does), and the script fails if any anchor
cannot be paired.

Usage: gen-client-roots.py <out.js> [<out.js> ...]
"""
import base64
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parents[1]
lock = (root / "Cargo.lock").read_text()
m = re.search(r'name = "webpki-roots"\nversion = "([^"]+)"', lock)
if not m:
    sys.exit("webpki-roots not in Cargo.lock")
version = m.group(1)
srcs = list(pathlib.Path.home().glob(f".cargo/registry/src/*/webpki-roots-{version}/src/lib.rs"))
if not srcs:
    sys.exit(f"webpki-roots {version} source not found (run cargo fetch in crypto/)")
text = srcs[0].read_text()



def rust_bytes(lit):
    """The bytes of a Rust byte-string literal body (the text inside b"...")."""
    out, i = bytearray(), 0
    simple = {"n": 10, "r": 13, "t": 9, "\\": 92, '"': 34, "'": 39, "0": 0}
    while i < len(lit):
        c = lit[i]
        if c != "\\":
            out += c.encode()
            i += 1
        elif lit[i + 1] == "x":
            out.append(int(lit[i + 2 : i + 4], 16))
            i += 4
        elif lit[i + 1] in simple:
            out.append(simple[lit[i + 1]])
            i += 2
        else:
            sys.exit(f"unknown escape in a webpki-roots byte string: {lit[i:i + 2]!r}")
    return bytes(out)


# Pair every TrustAnchor with the comment block (label and PEM) written just
# before it, and check the pairing: the anchor's subject must occur in that
# PEM's certificate. webpki applies an anchor's name_constraints (Mozilla's
# constraints, not in the certificate itself); the fork reads constraints only
# from certificate extensions, so a constrained anchor is left out (fail
# closed): the client then trusts no more than the sidecar does.
certs = []
skipped = []
comment = None  # the open comment block's lines
pending = None  # the last closed comment block, not yet paired
anchor = None  # the open TrustAnchor block's lines
anchors_seen = 0
for raw in text.splitlines():
    line = raw.strip()
    if anchor is not None:
        if line != "},":
            anchor.append(line)
            continue
        anchors_seen += 1
        if pending is None or "-----BEGIN CERTIFICATE-----" not in pending:
            sys.exit(f"trust anchor {anchors_seen} has no certificate comment before it")
        label = next((l.split(":", 1)[1].strip().strip('"') for l in pending if l.startswith("Label:")), "")
        a = pending.index("-----BEGIN CERTIFICATE-----")
        b = pending.index("-----END CERTIFICATE-----")
        pem_lines = pending[a : b + 1]
        der = base64.b64decode("".join(pem_lines[1:-1]))
        subj = [l for l in anchor if l.startswith("subject:")]
        nc = [l for l in anchor if l.startswith("name_constraints:")]
        m = re.fullmatch(r'subject: Der::from_slice\(b"(.*)"\),', subj[0]) if len(subj) == 1 else None
        if not m or len(nc) != 1:
            sys.exit(f"cannot parse trust anchor {anchors_seen} ({label})")
        if rust_bytes(m.group(1)) not in der:
            sys.exit(f"trust anchor {anchors_seen} ({label}): subject not in the certificate before it")
        if nc[0].rstrip(",") == "name_constraints: None":
            certs.append((label, "\n".join(pem_lines)))
        else:
            skipped.append(label)
        anchor = None
        pending = None
    elif comment is not None:
        if line == "*/":
            pending, comment = comment, None
        else:
            comment.append(line.lstrip("*").strip())
    elif line == "/*":
        comment = []
    elif line == "TrustAnchor {":
        anchor = []
anchors = text.count("TrustAnchor {")
if anchor is not None or comment is not None or anchors_seen != anchors or len(certs) + len(skipped) != anchors:
    sys.exit(f"found {len(certs)}+{len(skipped)} certificates for {anchors} trust anchors")

out = [
    "/* eslint indent: 0 */",
    "/**",
    " * Mozilla root store, generated by crypto/tools/gen-client-roots.py from",
    f" * webpki-roots {version} (the node's pinned copy of Mozilla's CCADB report),",
    " * so the client trusts only roots the node's sidecar trusts, and no more",
    " * widely. Do not edit by hand; re-run the script after a webpki-roots bump.",
]
if skipped:
    out += [
        " *",
        " * Left out: anchors webpki applies name constraints to (the fork cannot):",
    ] + [f" *   {label}" for label in skipped]
out += [
    " */",
    "export const MOZILLA_ROOT_CA_LIST = [",
]
for label, pem in certs:
    out.append(f"// {label}")
    out.append(f"`{pem}\n`,")
out.append("];")
body = "\n".join(out) + "\n"
for path in sys.argv[1:]:
    pathlib.Path(path).write_text(body)
print(f"webpki-roots {version}: {len(certs)} roots; left out (name-constrained): {skipped}")
