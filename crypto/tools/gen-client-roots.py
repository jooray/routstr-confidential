#!/usr/bin/env python3
"""Generate the TLS fork's bundled root store from the node's pinned webpki-roots.

The client (TLS fork, utils/mozilla-root-cas.js) and the node (cu-sidecar,
webpki-roots) must trust the same roots: a client that trusts more than the node
accepts certificates that only an honest node's own check would catch. This
reads the PEM certificates that webpki-roots embeds (generated by that crate
from Mozilla's CCADB report) for the version pinned in crypto/Cargo.lock and
writes them as the fork's MOZILLA_ROOT_CA_LIST.

Usage: gen-client-roots.py <out.js> [<out.js> ...]
"""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parents[1]
lock = (root / "Cargo.lock").read_text()
m = re.search(r'name = "webpki-roots"\nversion = "([^"]+)"', lock)
if not m:
    sys.exit("webpki-roots not in Cargo.lock")
version = m.group(1)
srcs = list(pathlib.Path.home().glob(f".cargo/registry/src/*/webpki-roots-{version}/src/lib.rs"))
if not srcs:
    sys.exit(f"webpki-roots {version} source not found (run cargo fetch in crypto/)")
text = srcs[0].read_text()

certs = []
for block in re.findall(r"/\*(.*?)\*/", text, re.S):
    lines = [l.strip().lstrip("*").strip() for l in block.splitlines()]
    if "-----BEGIN CERTIFICATE-----" not in lines:
        continue
    label = next((l.split(":", 1)[1].strip().strip('"') for l in lines if l.startswith("Label:")), "")
    a = lines.index("-----BEGIN CERTIFICATE-----")
    b = lines.index("-----END CERTIFICATE-----")
    certs.append((label, "\n".join(lines[a : b + 1])))
anchors = text.count("TrustAnchor {")
if len(certs) != anchors:
    sys.exit(f"found {len(certs)} certificates for {anchors} trust anchors")

out = [
    "/* eslint indent: 0 */",
    "/**",
    " * Mozilla root store, generated by crypto/tools/gen-client-roots.py from",
    f" * webpki-roots {version} (the node's pinned copy of Mozilla's CCADB report),",
    " * so the client trusts exactly the roots the node's sidecar trusts. Do not",
    " * edit by hand; re-run the script after a webpki-roots bump.",
    " */",
    "export const MOZILLA_ROOT_CA_LIST = [",
]
for label, pem in certs:
    out.append(f"// {label}")
    out.append(f"`{pem}\n`,")
out.append("];")
body = "\n".join(out) + "\n"
for path in sys.argv[1:]:
    pathlib.Path(path).write_text(body)
print(f"webpki-roots {version}: {len(certs)} roots")
