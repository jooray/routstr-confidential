/// Re-export the key schedule chain for the ZK circuit tests, so both use
/// identical native advice.
pub use keyschedule::KeySchedule as Schedule;
pub use hkdf::{expand_label, hkdf_extract};

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fixture_is_self_consistent() {
        let v = build();
        let mat = &v["epoch1_record_material"];
        let k1: [u8; 16] = hex(mat["K1"].as_str().unwrap()).try_into().unwrap();
        let iv1: [u8; 12] = hex(mat["IV1"].as_str().unwrap()).try_into().unwrap();
        let s = hex(mat["S"].as_str().unwrap());
        assert_eq!(s.len(), 251);
        let expect = aesgcm::ctr_keystream(&k1, &iv1, 0, 251);
        assert_eq!(s, expect);
    }
}
