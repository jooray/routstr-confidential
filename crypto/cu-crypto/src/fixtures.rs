/// A full fixture document: RFC 8448 key schedule, a synthetic credential
/// record's material and the NIST GCM vectors.
pub fn build() -> Value {
    let hs: [u8; 32] = hex("1dc826e93606aa6fdc0aadc12f741b01046aa6b99f691ed221a9f0ca043fbeac")
        .try_into()
        .unwrap();
    let th_sh: [u8; 32] = hex("860c06edc07858ee8e78f0e7428c58edd6b43f2ca3e6e95f02ed063cf0e1cad8")
        .try_into()
        .unwrap();
    let th_sf: [u8; 32] = hex("9608102a0f1ccc6db6250b7b7e417b1a000eaada3daae4777a7686c9ff83df13")
        .try_into()
        .unwrap();

    let ks = KeySchedule::from_handshake(hs, th_sh, th_sf);

    // Synthetic credential record: |head| = 251 bytes, epoch c_ap_1, seq 0.
    let head_len = 251usize;
    let k1 = ks.c_ap_1.key();
    let iv1 = ks.c_ap_1.iv();
    let seq = 0u64;
    let j0 = aesgcm::j0(&iv1, seq);
    let s = aesgcm::ctr_keystream(&k1, &iv1, seq, head_len);
    let h1 = aesgcm::ghash_key(&k1);
    let t0 = aesgcm::aes128_encrypt_block(&k1, &j0);

    json!({
        "note": "generated by cu-crypto/src/fixtures.rs; do not edit by hand",
        "rfc8448": {
            "hs": hx(&hs),
            "th_SH": hx(&th_sh),
            "th_SF": hx(&th_sf),
            "client_hs": hx(ks.client_hs.as_bytes()),
            "server_hs": hx(ks.server_hs.as_bytes()),
            "master_secret": hx(ks.master_secret.as_bytes()),
            "c_ap_0": hx(ks.c_ap_0.as_bytes()),
            "s_ap_0": hx(ks.s_ap_0.as_bytes()),
            "c_ap_1": hx(ks.c_ap_1.as_bytes()),
            "c_ap_2": hx(ks.c_ap_2.as_bytes()),
            "server_hs_key": hx(&ks.server_hs.key()),
            "server_hs_iv": hx(&ks.server_hs.iv()),
            "server_ap_key": hx(&ks.s_ap_0.key()),
            "server_ap_iv": hx(&ks.s_ap_0.iv()),
            "record": {
                "key": "3fce516009c21727d0f2e4e86ee403bc",
                "iv": "5d313eb2671276ee13000b30",
                "seq": 0,
                "plaintext_len": 658,
                "record_len": 679,
            }
        },
        "epoch1_record_material": {
            "head_len": head_len,
            "seq": seq,
            "K1": hx(&k1),
            "IV1": hx(&iv1),
            "J0": hx(&j0),
            "S": hx(&s),
            "H1": hx(&h1),
            "T0": hx(&t0),
            "header": hx(&aesgcm::record_header(head_len)),
        },
        "epoch2": {
            "K2": hx(&ks.c_ap_2.key()),
            "IV2": hx(&ks.c_ap_2.iv()),
        },
        "response": {
            "Ks": hx(&ks.s_ap_0.key()),
            "IVs": hx(&ks.s_ap_0.iv()),
        },
        "nist_gcm": nist_gcm_fixtures(),
        "nist_ghash": [
            { "H": "66e94bd4ef8a2c3b884cfa59ca342b2e", "data": "0388dace60b6a392f328c2b971b2fe78", "ghash": "f38cbb1ad69223dcc3457ae5b6b0f885" }
        ],
    })
}

fn hx(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

